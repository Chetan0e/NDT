def seed_database(db: Session, force: bool = False) -> dict:
    """
    Seeds the database with the sample cohort.
    If force is False and patients already exist, skipping is performed.
    """
    existing_count = db.query(Patient).count()
    if existing_count > 0 and not force:
        logger.info("Database already contains %d patients. Skipping seed.", existing_count)
        return {"status": "skipped", "message": f"Database already has {existing_count} patients", "patients_seeded": 0}

    if force:
        logger.info("Force seeding requested. Purging existing cohort records...")
        db.query(TherapySimulation).delete()
        db.query(GrowthRecord).delete()
        db.query(Scan).delete()
        db.query(Patient).delete()
        db.commit()

    seeded_patients = 0
    seeded_scans = 0

    for pdata in SAMPLE_PATIENTS:
        patient = Patient(
            patient_id=pdata["patient_id"],
            name=pdata["name"],
            age=pdata["age"],
            gender=pdata["gender"],
            diagnosis=pdata["diagnosis"],
            kps_score=pdata["kps_score"],
            tumor_grade=pdata["tumor_grade"],
            idh_mutation=pdata["idh_mutation"],
            mgmt_methylation=pdata["mgmt_methylation"],
            egfr_amplification=pdata["egfr_amplification"],
            tp53_mutation=pdata["tp53_mutation"],
            prior_treatments=pdata["prior_treatments"],
            created_at=datetime.now(timezone.utc),
        )
        db.add(patient)
        db.flush()

        # Add longitudinal scans
        for sdata in pdata.get("scans", []):
            scan = Scan(
                patient_id=pdata["patient_id"],
                scan_date=sdata["scan_date"],
                tumor_volume_mm3=sdata["tumor_volume_mm3"],
                tumor_volume_cc=sdata["tumor_volume_cc"],
                enhancing_volume=sdata.get("enhancing_volume"),
                necrotic_volume=sdata.get("necrotic_volume"),
                edema_volume=sdata.get("edema_volume"),
                dice_score=sdata.get("dice_score", 0.9),
                radiomics=sdata.get("radiomics"),
                patient_vector=sdata.get("patient_vector"),
                notes=sdata.get("notes"),
                created_at=datetime.now(timezone.utc),
            )
            db.add(scan)
            seeded_scans += 1

        # Add Growth Record
        g = pdata.get("growth")
        if g:
            gr = GrowthRecord(
                patient_id=pdata["patient_id"],
                growth_rate_alpha=g["growth_rate_alpha"],
                carrying_capacity=g["carrying_capacity"],
                treatment_sensitivity=g["treatment_sensitivity"],
                predicted_volume_30d=g["predicted_volume_30d"],
                predicted_volume_60d=g["predicted_volume_60d"],
                predicted_volume_90d=g["predicted_volume_90d"],
                growth_label=g["growth_label"],
                optimal_therapy=g["optimal_therapy"],
                therapy_score=g["therapy_score"],
                created_at=datetime.now(timezone.utc),
            )
            db.add(gr)

        # Add Therapy Simulation
        sim = pdata.get("simulation")
        if sim:
            ts = TherapySimulation(
                patient_id=pdata["patient_id"],
                initial_volume=sim["initial_volume"],
                simulation_days=sim["simulation_days"],
                best_therapy=sim["best_therapy"],
                therapy_intensity=sim["therapy_intensity"],
                final_volume=sim["final_volume"],
                volume_reduction_pct=sim["volume_reduction_pct"],
                strategy_comparison=sim["strategy_comparison"],
                created_at=datetime.now(timezone.utc),
            )
            db.add(ts)

        seeded_patients += 1

    db.commit()
    logger.info("Successfully seeded %d patients and %d scans.", seeded_patients, seeded_scans)
    return {
        "status": "success",
        "patients_seeded": seeded_patients,
        "scans_seeded": seeded_scans,
        "message": f"Successfully loaded clinical demo cohort with {seeded_patients} patients and {seeded_scans} scans."
    }
